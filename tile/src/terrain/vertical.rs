/// Datum declarations of one DEM source, as read from the config JSON.
#[derive(Debug, Default)]
pub struct SourceDeclaration<'a> {
    /// Source-level `verticalDatum` (default for every layer).
    pub default_datum: Option<&'a str>,
    /// Per built overlay (bottom → top): the layer's own `verticalDatum`.
    pub layer_datums: Vec<Option<&'a str>>,
    /// Source-level `heightCorrection`, unparsed.
    pub correction: Option<&'a serde_json::Value>,
}

impl SourceDeclaration<'_> {
    fn is_empty(&self) -> bool {
        self.default_datum.is_none()
            && self.layer_datums.iter().all(Option::is_none)
            && self.correction.is_none()
    }
}

/// What [`plan_source`] decided for a source.
#[derive(Debug, PartialEq)]
pub enum DatumPlan {
    /// Nothing declared: build the source exactly as before.
    Legacy,
    /// Datums declared and consistent; correct the flagged members.
    Checked {
        target: VerticalDatum,
        /// The datum ΔH must convert *from* (the one that is not the target),
        /// when anything needs correcting.
        from: Option<VerticalDatum>,
        base_corrected: bool,
        layer_corrected: Vec<bool>,
        /// `(manifest URL, policy)`, set only when something is corrected.
        correction: Option<(String, MissingDhPolicy)>,
    },
}

/// Check a source's datum declarations against its geoid and the base, and
/// decide which members get ΔH. Any combination that cannot be served
/// correctly is an `Err` naming the reason; the caller refuses the source.
pub fn plan_source(
    geoid: GeoidModel,
    decl: &SourceDeclaration<'_>,
    base: BaseDatum,
) -> Result<DatumPlan, String> {
    if decl.is_empty() {
        return Ok(DatumPlan::Legacy);
    }
    let target = geoid.target_datum().ok_or_else(|| {
        format!(
            "geoid `{geoid}` is not bound to an orthometric datum (only gsigeo2011 → jgd2011 \
             and jpgeo2024-hrefconv → jgd2024 are), so this source cannot declare \
             verticalDatum / heightCorrection"
        )
    })?;
    let default: Option<VerticalDatum> = decl
        .default_datum
        .map(str::parse)
        .transpose()
        .map_err(|e| format!("verticalDatum: {e}"))?;
    let mut layers = Vec::with_capacity(decl.layer_datums.len());
    for (i, d) in decl.layer_datums.iter().enumerate() {
        let d = match d {
            Some(s) => s
                .parse()
                .map_err(|e| format!("layers[{i}].verticalDatum: {e}"))?,
            None => default.ok_or_else(|| {
                format!(
                    "layers[{i}] has no vertical datum (set verticalDatum on the source or the layer)"
                )
            })?,
        };
        layers.push(d);
    }
    let correction: Option<(HeightCorrectionConfig, MissingDhPolicy)> = match decl.correction {
        None => None,
        Some(v) => {
            let c: HeightCorrectionConfig =
                serde_json::from_value(v.clone()).map_err(|e| format!("heightCorrection: {e}"))?;
            let policy = c
                .missing
                .as_deref()
                .map(str::parse)
                .transpose()?
                .unwrap_or_default();
            Some((c, policy))
        }
    };

    let base_corrected = match base {
        BaseDatum::Agnostic => false,
        BaseDatum::Known(d) => d != target,
        BaseDatum::Unknown if correction.is_some() => {
            return Err(
                "the base DEM's vertical datum is unknown: set DEM_VERTICAL_DATUM (jgd2011 | \
                 jgd2024) for the DEM_URL upstream, or use DEM_URL=sealevel, before a source \
                 can apply a height correction"
                    .to_string(),
            );
        }
        BaseDatum::Unknown => {
            tracing::warn!(
                "a DEM source declares vertical datums on a base of unknown datum \
                 (DEM_VERTICAL_DATUM unset); base pixels are served as-is"
            );
            false
        }
    };
    let layer_corrected: Vec<bool> = layers.iter().map(|d| *d != target).collect();
    let needs = base_corrected || layer_corrected.iter().any(|&c| c);
    if !needs {
        if correction.is_some() {
            tracing::warn!(
                "heightCorrection configured but every layer is already {target}; it is not applied"
            );
        }
        return Ok(DatumPlan::Checked {
            target,
            from: None,
            base_corrected,
            layer_corrected,
            correction: None,
        });
    }
    // Only two datums exist, so everything to correct is in the other one.
    let from = match target {
        VerticalDatum::Jgd2011 => VerticalDatum::Jgd2024,
        VerticalDatum::Jgd2024 => VerticalDatum::Jgd2011,
    };
    let Some((c, policy)) = correction else {
        let what: Vec<String> = base_corrected
            .then(|| "the base DEM".to_string())
            .into_iter()
            .chain(
                layer_corrected
                    .iter()
                    .enumerate()
                    .filter(|(_, c)| **c)
                    .map(|(i, _)| format!("layers[{i}]")),
            )
            .collect();
        return Err(format!(
            "{} {} {from} but the geoid `{geoid}` expects {target}, and no heightCorrection is \
             configured",
            what.join(", "),
            if what.len() == 1 { "is" } else { "are" },
        ));
    };
    Ok(DatumPlan::Checked {
        target,
        from: Some(from),
        base_corrected,
        layer_corrected,
        correction: Some((c.manifest, policy)),
    })
}

/// Check that a loaded product converts exactly `from → target`.
pub fn check_product(
    product: &DhProduct,
    from: VerticalDatum,
    target: VerticalDatum,
) -> Result<(), String> {
    if product.from == from && product.to == target {
        return Ok(());
    }
    if product.from == target && product.to == from {
        return Err(format!(
            "{} converts {} → {}, but this source needs {from} → {target} (no inverse \
             correction is available)",
            product.key(),
            product.from,
            product.to
        ));
    }
    Err(format!(
        "{} converts {} → {}, but this source needs {from} → {target}",
        product.key(),
        product.from,
        product.to
    ))
}

// ─────────────────────────────── Applying ───────────────────────────────

/// The correction a composite DEM applies: which members, with which product.
pub struct SourceCorrection {
    pub product: Arc<DhProduct>,
    pub policy: MissingDhPolicy,
    pub base: bool,
    /// Per overlay, in composite order.
    pub layers: Vec<bool>,
    descriptor: String,
}

impl SourceCorrection {
    pub fn new(
        product: Arc<DhProduct>,
        policy: MissingDhPolicy,
        base: bool,
        base_datum: BaseDatum,
        layers: Vec<bool>,
    ) -> Self {
        let mask: String = layers.iter().map(|&c| if c { '1' } else { '0' }).collect();
        let descriptor = format!(
            "vcorr={key}:{from}-to-{to}:missing={policy}:base={base_datum}:base-dh={base_flag}:layers={mask:x}",
            key = product.key(),
            from = product.from,
            to = product.to,
            policy = policy.slug(),
            base_datum = base_datum.slug(),
            base_flag = if base { "yes" } else { "no" },
            mask = xxh64(mask.as_bytes(), 0),
        );
        Self {
            product,
            policy,
            base,
            layers,
            descriptor,
        }
    }

    /// Cache-key / ETag fragment: product id + version, the missing-ΔH
    /// policy, and which members are corrected. Only sources that apply a
    /// correction carry it, so every other source keeps its keys.
    pub fn descriptor(&self) -> &str {
        &self.descriptor
    }

    /// Add ΔH to every finite elevation of `tile`, which was evaluated for
    /// tile `z/x/y` (the zoom the member was actually asked for).
    pub fn apply(
        &self,
        tile: &mut DemTile,
        z: u8,
        x: u32,
        y: u32,
        tile_size: u32,
        memo: &mut DhMemo,
    ) {
        let positions = tile
            .positions
            .unwrap_or_else(|| PixelPositions::centres(tile_size));
        let grid = memo.grid(positions, z, x, y, tile_size);
        let n = tile_size as usize;
        for (idx, v) in tile.elevations.iter_mut().enumerate() {
            if !v.is_finite() {
                continue;
            }
            let dh = grid.get(&self.product.selection, idx % n, idx / n);
            if dh.is_finite() {
                *v += dh;
            } else if self.policy == MissingDhPolicy::Nan {
                *v = f64::NAN;
            }
        }
    }
}

