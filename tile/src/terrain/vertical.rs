/// An orthometric-height datum (the 標高 a DEM value is expressed in).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum VerticalDatum {
    /// 測地成果2011 heights.
    Jgd2011,
    /// 測地成果2024 heights (GSI's 2025 標高改定).
    Jgd2024,
}

impl VerticalDatum {
    pub fn slug(&self) -> &'static str {
        match self {
            Self::Jgd2011 => "jgd2011",
            Self::Jgd2024 => "jgd2024",
        }
    }
}

impl fmt::Display for VerticalDatum {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.slug())
    }
}

impl FromStr for VerticalDatum {
    type Err = String;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s.trim().to_ascii_lowercase().as_str() {
            "jgd2011" => Ok(Self::Jgd2011),
            "jgd2024" => Ok(Self::Jgd2024),
            other => Err(format!(
                "unknown vertical datum `{other}` (valid: jgd2011, jgd2024)"
            )),
        }
    }
}

/// Datum of the shared base DEM (`DEM_URL`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BaseDatum {
    /// Declared by the operator (`DEM_VERTICAL_DATUM`).
    Known(VerticalDatum),
    /// The sea-level base: "no data → 0 m orthometric = mean sea level". It is
    /// not a height in either datum, so it is never corrected — adding ±0.4 m
    /// of ΔH would warp the sea surface.
    Agnostic,
    /// A real upstream whose datum nobody declared. Sources that apply a
    /// correction refuse to build on it.
    Unknown,
}

impl BaseDatum {
    /// Resolve the base datum for `DEM_URL` (`is_sea_level`) and the
    /// `DEM_VERTICAL_DATUM` env value.
    pub fn resolve(is_sea_level: bool, declared: Option<&str>) -> Self {
        let declared = declared.map(str::trim).filter(|s| !s.is_empty());
        if is_sea_level {
            if let Some(d) = declared {
                tracing::warn!(
                    DEM_VERTICAL_DATUM = %d,
                    "ignored: the sea-level base is datum-agnostic and is never height-corrected"
                );
            }
            return Self::Agnostic;
        }
        match declared.map(str::parse::<VerticalDatum>) {
            None => Self::Unknown,
            Some(Ok(d)) => Self::Known(d),
            Some(Err(e)) => {
                tracing::error!(
                    error = %e,
                    "DEM_VERTICAL_DATUM is invalid; the base DEM datum is treated as unknown \
                     and sources with a heightCorrection will be refused"
                );
                Self::Unknown
            }
        }
    }

    fn slug(&self) -> &'static str {
        match self {
            Self::Known(d) => d.slug(),
            Self::Agnostic => "agnostic",
            Self::Unknown => "unknown",
        }
    }
}

/// What to do with an elevation that needs a correction where the product has
/// no ΔH (outside its grids: the Northern Territories, Iwo-to, the Senkaku
/// islands, Nanatsu-jima, the open sea, …).
///
/// **Pending a policy decision** — `keep` is the default only because it does
/// not change what is served today; the choice is part of every cache key.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum MissingDhPolicy {
    /// Serve the elevation uncorrected.
    #[default]
    Keep,
    /// Drop the pixel (NaN), so lower layers — ultimately the base — show
    /// through.
    Nan,
}

impl MissingDhPolicy {
    pub fn slug(&self) -> &'static str {
        match self {
            Self::Keep => "keep",
            Self::Nan => "nan",
        }
    }
}

impl FromStr for MissingDhPolicy {
    type Err = String;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s.trim().to_ascii_lowercase().as_str() {
            "keep" => Ok(Self::Keep),
            "nan" => Ok(Self::Nan),
            other => Err(format!(
                "unknown heightCorrection.missing `{other}` (valid: keep, nan)"
            )),
        }
    }
}

/// `heightCorrection` of a DEM source in the config JSON.
#[derive(Debug, Clone, Deserialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct HeightCorrectionConfig {
    /// URL of the correction product's `manifest.json` (https, gs, s3, r2,
    /// file). The product version is part of the URL, so swapping versions is
    /// a config change.
    pub manifest: String,
    /// [`MissingDhPolicy`]: `keep` (default) or `nan`.
    #[serde(default)]
    pub missing: Option<String>,
}

