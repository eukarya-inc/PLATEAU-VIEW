//! Vertical datums of DEM layers, and the on-the-fly height correction that
//! brings every layer of a source onto the datum its geoid expects.
//!
//! # Model
//!
//! - A source's **target datum** follows from its geoid model
//!   ([`GeoidModel::target_datum`]): GSIGEO2011 → JGD2011,
//!   JPGEO2024+Hrefconv2024 → JGD2024. The geoid is still added once, at the
//!   end, exactly as before.
//! - Every DEM **layer** has a datum: the layer's `verticalDatum`, else the
//!   source's `verticalDatum` (so a whole stack is declared at once).
//! - The **base** DEM has a [`BaseDatum`]: a real upstream is `jgd2011` /
//!   `jgd2024` only when the operator says so (`DEM_VERTICAL_DATUM`); the
//!   sea-level base is [`BaseDatum::Agnostic`] — "no data → 0 m = mean sea
//!   level" is not a JGD2011 or JGD2024 height and is never corrected.
//! - A layer (or the base) whose datum differs from the target gets
//!   `ΔH(p)` added to each of its elevations **before** the priority composite
//!   (`paint_over`), so the composite is homogeneous. ΔH comes from a
//!   correction **product** the source names by its manifest URL
//!   (`heightCorrection.manifest`), e.g. GSI's JGD2011 → JGD2024 標高補正
//!   parameters as published by `tile/scripts/vertical-cogs`.
//! - Anything that cannot be served correctly is refused when the config is
//!   loaded ([`plan_source`]) — a datum with no correction to the target, an
//!   inverse correction we do not have, a geoid without a datum, an unknown
//!   base under a correction — rather than passed through.
//!
//! A source that declares none of this (`verticalDatum`, `heightCorrection`)
//! is untouched: [`DatumPlan::Legacy`] builds exactly the provider it always
//! did, with the same cache keys.
//!
//! # Sampling
//!
//! [`sample`] and [`DhProduct::sample`] are a line-by-line port of the
//! normative reference `tile/scripts/vertical-cogs/sampler.py` (`sample`,
//! `mesh6_of`, `DhGsi`); the golden test pins them to vectors generated by it.

