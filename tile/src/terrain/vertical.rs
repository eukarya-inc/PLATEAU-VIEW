    /// Parse Python's `float.hex()` (`[-]0x1.<hex>p<exp>`, or `0x0.0p+0`).
    fn parse_hex_float(s: &str) -> f64 {
        let (neg, s) = s.strip_prefix('-').map_or((false, s), |r| (true, r));
        let s = s.strip_prefix("0x").expect("0x prefix");
        let (mant, exp) = s.split_once('p').expect("p exponent");
        let (int, frac) = mant.split_once('.').unwrap_or((mant, ""));
        let mut v = u64::from_str_radix(int, 16).unwrap() as f64;
        let mut scale = 1.0 / 16.0;
        for c in frac.chars() {
            v += c.to_digit(16).unwrap() as f64 * scale;
            scale /= 16.0;
        }
        let v = v * 2f64.powi(exp.parse::<i32>().unwrap());
        if neg { -v } else { v }
    }

    #[test]
    fn hex_float_parser_is_exact() {
        assert_eq!(parse_hex_float("0x0.0p+0"), 0.0);
        assert_eq!(parse_hex_float("0x1.0640000000000p+7"), 131.125);
        assert_eq!(parse_hex_float("0x1.f89108334ec72p+4"), 31.535408211155705);
        assert_eq!(
            parse_hex_float("-0x1.0354dc69d6a27p-3"),
            -0.1266267032431909
        );
    }

