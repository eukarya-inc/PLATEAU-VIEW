    /// A [`NodeGrid`] that records every node `sample` reads.
    struct Recording<'a> {
        inner: &'a Float32Raster,
        seen: std::cell::RefCell<std::collections::BTreeMap<(i64, i64), Option<f64>>>,
    }

    impl NodeGrid for Recording<'_> {
        fn x0(&self) -> f64 {
            self.inner.x0
        }
        fn y0(&self) -> f64 {
            self.inner.y0
        }
        fn dx(&self) -> f64 {
            self.inner.dx
        }
        fn dy(&self) -> f64 {
            self.inner.dy
        }
        fn width(&self) -> u32 {
            self.inner.width
        }
        fn height(&self) -> u32 {
            self.inner.height
        }
        fn get(&self, row: i64, col: i64) -> Option<f64> {
            let v = self.inner.get(row, col);
            self.seen.borrow_mut().insert((row, col), v);
            v
        }
    }

