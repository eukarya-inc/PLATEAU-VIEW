"""Generate cms_assets_unit_price.sql from a Cloud Billing export.

Averages a month of the delivery SKUs' net cost (cost plus credits) per pricing unit
and prints the unit_price view's SQL. The prices are the project's own, so the
generated file is not kept in this repository.

    uv run unit_price.py --billing-table PROJECT.DATASET.gcp_billing_export_v1_XXXX \
        --project reearth-plateau --month 2026-09 > cms_assets_unit_price.sql

Needs the bq CLI with read access to the billing export.
"""

import argparse
import datetime
import json
import math
import subprocess
import sys

# Regions each item needs; they match the country_region view.
REGIONS = {
    "cdn_egress": ["Asia", "Europe", "North America", "China", "Oceania", "Latin America", "Other"],
    "internet_egress": ["Apac", "EMEA", "Americas", "China", "South America", "Australia", "Middle East", "Africa"],
    "cache_fill": ["Asia", "Europe", "North America", "China", "Oceania", "Latin America", "Other"],
    "cache_lookup": [""],
    "gcs_class_b": [""],
    "storage": [""],
}

QUERY = """
SELECT
  CASE
    WHEN sku.description LIKE "Networking Cloud CDN Traffic Cache Data Transfer to %" THEN "cdn_egress"
    WHEN service.description = "Compute Engine"
      AND REGEXP_CONTAINS(sku.description, r"^Network Internet Data Transfer Out from (Tokyo|Japan) to ") THEN "internet_egress"
    WHEN service.description = "Cloud Storage" AND sku.description LIKE "Cloud CDN %Cache Fill%" THEN "cache_fill"
    WHEN sku.description = "Networking Cloud Cdn Cache Lookups" THEN "cache_lookup"
    WHEN sku.description = "Dual-Region Standard Class B Operations" THEN "gcs_class_b"
    WHEN sku.description = "Standard Storage Osaka/Tokyo Dual-region" THEN "storage"
  END AS item,
  CASE
    WHEN sku.description LIKE "%Cache Data Transfer to %" THEN REGEXP_EXTRACT(sku.description, r"Cache Data Transfer to (.+)$")
    WHEN sku.description LIKE "%Data Transfer Out from % to Apac%" THEN "Apac"
    WHEN sku.description LIKE "%Data Transfer Out from % to %" THEN REGEXP_EXTRACT(sku.description, r" to (.+)$")
    WHEN sku.description LIKE "%Intra-Region Cache Fill" THEN "Asia"
    WHEN sku.description LIKE "%Cache Fill from Asia Pacific to %" THEN REGEXP_EXTRACT(sku.description, r" to (.+)$")
    ELSE ""
  END AS region,
  SAFE_DIVIDE(
    SUM(cost) + SUM(IFNULL((SELECT SUM(c.amount) FROM UNNEST(credits) c), 0)),
    SUM(usage.amount_in_pricing_units)) AS unit_price
FROM `{table}`
WHERE project.id = "{project}"
  AND usage_start_time >= TIMESTAMP("{start}") AND usage_start_time < TIMESTAMP("{end}")
GROUP BY item, region
HAVING item IS NOT NULL AND unit_price > 0
"""

HEADER = """\
-- Estimated unit prices (JPY, net of credits) of the SKUs used to deliver CMS assets.
-- Averages of {project}'s {month} billing, generated by analytics/cms-assets/scripts/unit_price.py.
-- The SKUs are shared with other backends and billed in volume tiers, so these are estimates,
-- not invoice amounts.
--
-- item:
--   cdn_egress       "Networking Cloud CDN Traffic Cache Data Transfer to <region>" (per GiB)
--   internet_egress  Compute Engine "Network Internet Data Transfer Out from Tokyo/Japan to <region>" (per GiB);
--                    responses Cloud CDN cannot cache, e.g. objects over 100 GiB
--   cache_fill       Cloud Storage "Cloud CDN ... Cache Fill" (per GiB); "Asia" is intra-region
--   cache_lookup     "Networking Cloud Cdn Cache Lookups" (per request)
--   gcs_class_b      "Dual-Region Standard Class B Operations" (per request)
--   storage          "Standard Storage Osaka/Tokyo Dual-region" (per GiB-month)
"""


def month_range(month: str) -> tuple[str, str]:
    start = datetime.date.fromisoformat(month + "-01")
    end = (start + datetime.timedelta(days=32)).replace(day=1)
    return start.isoformat(), end.isoformat()


def fetch(table: str, project: str, start: str, end: str) -> dict[tuple[str, str], float]:
    query = QUERY.format(table=table, project=project, start=start, end=end)
    out = subprocess.run(
        ["bq", "query", "--quiet", "--use_legacy_sql=false", "--format=json", f"--project_id={project}", query],
        check=True, capture_output=True, text=True,
    ).stdout
    return {(r["item"], r["region"]): float(r["unit_price"]) for r in json.loads(out)}


def format_price(v: float) -> str:
    # Two decimals for per-GiB prices, two significant digits for per-request ones.
    decimals = 2 if v >= 1 else 1 - math.floor(math.log10(v))
    return f"{v:.{decimals}f}"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--billing-table", required=True, help="Cloud Billing export table (PROJECT.DATASET.TABLE)")
    p.add_argument("--project", required=True, help="project whose billing to average")
    p.add_argument("--month", required=True, help="month to average, YYYY-MM")
    args = p.parse_args()

    prices = fetch(args.billing_table, args.project, *month_range(args.month))

    rows, notes, missing = [], [], []
    for item, regions in REGIONS.items():
        for region in regions:
            price = prices.get((item, region))
            if price is None and item == "cache_fill" and region != "Asia":
                # Regions without fills that month use the average inter-region rate.
                others = [v for (i, r), v in prices.items() if i == item and r != "Asia"]
                if others:
                    price = sum(others) / len(others)
                    notes.append(region)
            if price is None:
                missing.append(f"{item}/{region or '-'}")
                continue
            rows.append(f'  ("{item}", "{region}", {format_price(price)})')

    if missing:
        sys.exit(f"no billing for {', '.join(missing)} in {args.month}; pick another month")

    header = HEADER.format(project=args.project, month=args.month)
    if notes:
        header += f"--   cache_fill regions without fills in {args.month} use the inter-region rate: {', '.join(notes)}\n"
    print(header + "SELECT * FROM UNNEST(ARRAY<STRUCT<item STRING, region STRING, unit_price_jpy FLOAT64>>[")
    print(",\n".join(rows))
    print("])")


if __name__ == "__main__":
    main()
